// generated_tables.go reconstructs mathematical lookup tables without original
// game files. The emitted C initializers are build output, not runtime code.
package main

import (
	"bytes"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"sync"
)

// An octave contains twelve semitones, each with 256 fine pitch steps. The
// reference pitch is 8192; the sequencer shifts it for the requested octave.
func suzukiPitchTable() []uint16 {
	values := make([]uint16, 12*256)
	for i := range values {
		values[i] = uint16(math.Floor(8192*math.Exp2(float64(i)/float64(len(values))) + 0.5))
	}
	return values
}

var suzukiPitchInitializer = sync.OnceValue(func() []byte {
	var out bytes.Buffer
	out.WriteString("/* Generated by tools/generated_tables.go: round(8192 * 2^(i / 3072)). */\n")
	for i, value := range suzukiPitchTable() {
		if i%16 == 0 {
			out.WriteString("    ")
		}
		fmt.Fprintf(&out, "%d,", value)
		if i%16 == 15 {
			out.WriteByte('\n')
		} else {
			out.WriteByte(' ')
		}
	}
	return out.Bytes()
})

// Keep generation independent of extracted files. Compare before writing so
// repeated invocations preserve timestamps; rename atomically for other tools
// that may be preprocessing the same include concurrently.
func (p project) generateTables() error {
	dir := filepath.Join(p.root, "build", "generated")
	path := filepath.Join(dir, "suzuki_pitch.inc")
	want := suzukiPitchInitializer()
	if got, err := os.ReadFile(path); err == nil && bytes.Equal(got, want) {
		return nil
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	file, err := os.CreateTemp(dir, ".suzuki-pitch-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(want); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}
